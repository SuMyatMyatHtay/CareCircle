import { test, expect, login } from './fixtures.mjs'

const password = 'CareCircle-test-only-123'
async function fillSignup(page, email) {
  await page.getByLabel('Full name', { exact: false }).fill('New Caregiver')
  await page.getByLabel('Email address', { exact: false }).fill(email)
  await page.getByLabel(/^Password/).fill(password)
  await page.getByLabel('Confirm password', { exact: false }).fill(password)
  await page.getByRole('checkbox').check()
}

test.describe('Account registration and family onboarding', () => {
  test('validates signup fields and handles an existing email without signing in', async ({ page }) => {
    await page.goto('/signup')
    const submit = page.getByRole('button', { name: 'Create account', exact: false })
    await submit.click()
    await expect(page.getByText('Enter a name between 2 and 80 characters.', { exact: true })).toBeVisible()
    await expect(page.getByText('Please tick the box to continue.', { exact: true })).toBeVisible()
    await fillSignup(page, 'alex@carecircle.test')
    await page.getByLabel('Confirm password', { exact: false }).fill('different-password')
    await submit.click()
    await expect(page.getByText('Passwords must match.', { exact: true })).toBeVisible()
    await page.getByLabel('Confirm password', { exact: false }).fill(password)
    const response = page.waitForResponse(res => res.url().endsWith('/auth/register') && res.request().method() === 'POST')
    await submit.click()
    expect((await response).status()).toBe(409)
    await expect(page.getByRole('alert')).toContainText('An account with this email already exists.')
    await expect(page).toHaveURL(/\/signup$/)
    expect(await page.evaluate(() => sessionStorage.getItem('token'))).toBeNull()
  })

  test('registers, creates a family, and lets another caregiver join with member permissions', async ({ page, isMobile }) => {
    await page.goto('/signup')
    await fillSignup(page, 'new-caregiver@carecircle.test')
    await page.getByLabel('Language', { exact: true }).selectOption('zh')
    await page.getByRole('button', { name: 'Create account', exact: false }).click()
    await expect(page).toHaveURL(/\/home$/)
    await expect(page.getByRole('heading', { name: 'Your circle starts here', exact: true }).filter({ visible: true })).toBeVisible()
    await page.getByRole('link', { name: 'Create a family', exact: true }).filter({ visible: true }).click()
    const create = page.getByRole('button', { name: 'Create my family', exact: false })
    await expect(create).toBeDisabled()
    await page.getByLabel('What should we call your family?', { exact: true }).fill('New caregiver family')
    const response = page.waitForResponse(res => /\/api\/families\/?$/.test(res.url()) && res.request().method() === 'POST')
    await create.click()
    const created = await response
    expect(created.status()).toBe(201)
    const { family } = await created.json()
    expect(family.inviteCode).toMatch(/^[A-F0-9]{10}$/)
    await expect(page.getByRole('heading', { name: family.inviteCode, exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Back to home →', exact: true }).click()
    await page.goto('/settings')
    if (isMobile) await expect(page.getByLabel('Notes language', { exact: true })).toHaveValue('zh')
    else await expect(page.getByRole('button', { name: '中文', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByRole('button', { name: isMobile ? 'Regenerate invite code' : 'Regenerate', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: /Log out/ }).click()
    await expect(page).toHaveURL(/\/login$/)

    await login(page, 'may')
    await page.goto('/join-family')
    const input = page.getByLabel("What's your family invitation code?", { exact: true })
    const join = page.getByRole('button', { name: 'Join my family', exact: false })
    await input.fill('invalid')
    await expect(join).toBeDisabled()
    await input.fill(family.inviteCode.toLowerCase())
    await expect(input).toHaveValue(family.inviteCode)
    await join.click()
    await expect(page.getByRole('heading', { name: 'Welcome to the family! ♡', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Go to my family', exact: false }).click()
    await expect(page).toHaveURL(/\/home$/)
    await page.goto('/settings')
    const invitation = page.getByRole('region', { name: isMobile ? 'Family invite code' : 'Invite code', exact: true })
    await expect(invitation).toContainText(family.inviteCode)
    await expect(page.getByRole('listitem').filter({ hasText: 'New Caregiver' }).filter({ visible: true })).toContainText('Admin')
    await expect(page.getByRole('listitem').filter({ hasText: 'Aunt May' }).filter({ visible: true })).toContainText('Member')
    await expect(page.getByRole('button', { name: isMobile ? 'Regenerate invite code' : 'Regenerate', exact: true })).toBeDisabled()
    await page.reload()
    await expect(invitation).toContainText(family.inviteCode)
  })
})
