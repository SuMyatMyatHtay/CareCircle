import { test, expect, ids, login, authenticatedApi } from './fixtures.mjs'
import { recurringTaskPayload } from '../support/recurring-fixtures.mjs'

const visibleButton = (page, name) => page.getByRole('button', { name, exact: true }).filter({ visible: true })

test('New task stays directly available on Home across phone and desktop breakpoints', async ({ page }) => {
  await login(page)
  for (const width of [320, 390, 767, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/home')
    const create = visibleButton(page, 'New task')
    await expect(create).toHaveCount(1)
    if (width === 320 || width === 390) await page.screenshot({ path: test.info().outputPath(`home-${width}.png`) })
    await create.click()
    if (width < 768) {
      await expect(page).toHaveURL(/\/tasks\/new$/)
      await expect(page.getByLabel('What needs doing?')).toBeVisible()
    } else {
      const dialog = page.getByRole('dialog', { name: 'New task', exact: true })
      await expect(dialog).toBeVisible()
      await dialog.getByRole('button', { name: 'Close', exact: true }).click()
      await expect(dialog).not.toBeVisible()
    }
  }
})

test('mobile Home exposes recipient actions, task filters and left-menu destinations', async ({ page, isMobile, isolatedData }) => {
  test.skip(!isMobile, 'Phone action access')
  const api = await authenticatedApi(page, isolatedData.apiURL)
  const result = await api(`/families/${ids.family}/tasks`, { method: 'POST', data: {
    title: 'Future recipient care', category: 'other', recipient: ids.grandpa,
    startAt: new Date(Date.now() + 2 * 86400000).toISOString(),
  } })
  expect(result.status()).toBe(201)
  await login(page)
  await page.setViewportSize({ width: 320, height: 844 })
  await visibleButton(page, 'Care recipients').click()
  let dialog = page.getByRole('dialog', { name: 'Your family circle' })
  await expect(dialog.getByRole('link', { name: 'Add care recipient' })).toBeVisible()
  await expect(dialog.getByRole('link', { name: 'View family members' })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Open hub' })).toBeVisible()
  await dialog.getByRole('button', { name: /needs? someone/ }).click()
  dialog = page.getByRole('dialog', { name: 'Family tasks', exact: true })
  await expect(dialog).toContainText('Future recipient care')
  await expect(dialog.getByRole('button', { name: 'Clear', exact: true })).toBeVisible()
  for (const filter of ['Upcoming', 'Today', 'Needs someone', 'Overdue', 'Claimed', 'In progress', 'Completed', 'All tasks']) {
    await expect(dialog.getByRole('button', { name: filter, exact: true })).toBeVisible()
  }
  await dialog.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Open navigation menu' }).click()
  const menu = page.locator('#family-navigation')
  for (const name of ['Family home', 'My tasks', 'Calendar', 'Contributions', 'Add care recipient', 'Family settings']) {
    await expect(menu.getByRole('link', { name, exact: true })).toBeVisible()
  }
  await menu.locator('.family-selector').click()
  for (const name of ['Create a new family', 'Join with invite code']) {
    await expect(menu.getByRole('link', { name, exact: true })).toBeVisible()
  }
  await page.keyboard.press('Escape')
  await visibleButton(page, 'Care recipients').click()
  await page.getByRole('dialog', { name: 'Your family circle' }).getByRole('link', { name: 'Add care recipient' }).click()
  await expect(page).toHaveURL(/\/recipients\/new$/)
  await expect(page.getByLabel('Full name', { exact: true })).toBeVisible()
})

test('mobile Home can edit, pause and resume a household repeating task', async ({ page, isMobile, isolatedData }) => {
  test.skip(!isMobile, 'Phone series controls')
  const api = await authenticatedApi(page, isolatedData.apiURL)
  const base = `/families/${ids.family}/tasks`
  const created = await api(base, { method: 'POST', data: recurringTaskPayload({ count: 3 }) })
  expect(created.status()).toBe(201)
  const { task } = await created.json()
  await login(page)
  await page.setViewportSize({ width: 320, height: 844 })
  const panel = page.locator('.care-home-mobile .recurring-series-panel')
  await panel.getByRole('button', { name: 'Edit', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Edit repeating task' })
  await expect(edit.getByLabel('What needs doing?')).toHaveValue(task.title)
  await edit.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(edit).not.toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await panel.getByRole('button', { name: 'Stop repeating', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Resume', exact: true })).toBeVisible()
  await page.reload()
  await panel.getByRole('button', { name: 'Resume', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Stop repeating', exact: true })).toBeVisible()
  const response = await api(base)
  const tasks = (await response.json()).tasks.filter(t => t.recurringSeries === task.recurringSeries)
  expect(tasks).toHaveLength(3)
  expect(tasks.every(t => t.status === 'open')).toBe(true)
})

test('phones can match device appearance and use every search filter', async ({ page, isMobile }) => {
  test.skip(!isMobile, 'Phone preferences and search filters')
  await page.emulateMedia({ colorScheme: 'dark' })
  await login(page)
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto('/settings')
  await visibleButton(page, 'Match my device').click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(visibleButton(page, 'Match my device')).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/search?q=Grandpa')
  const cancelBounds = await page.getByRole('button', { name: 'Cancel', exact: true }).boundingBox()
  expect(cancelBounds.x + cancelBounds.width).toBeLessThanOrEqual(320)
  await page.getByText('Filters and sort', { exact: true }).click()
  const filters = page.getByRole('group', { name: 'Search filters', exact: true })
  await page.screenshot({ path: test.info().outputPath('search-filters-320.png') })
  await filters.getByLabel('For', { exact: true }).selectOption(ids.grandpa)
  await filters.getByLabel('When', { exact: true }).selectOption('upcoming')
  await filters.getByLabel('Task status', { exact: true }).selectOption('open')
  await filters.getByLabel('Sort', { exact: true }).selectOption('newest')
  await expect(page).toHaveURL(/recipient=/)
  await expect(page).toHaveURL(/when=upcoming/)
  await expect(page).toHaveURL(/status=open/)
  await expect(page).toHaveURL(/sort=newest/)
  await page.reload()
  await page.getByText(/Filters and sort/).click()
  await expect(filters.getByLabel('For', { exact: true })).toHaveValue(ids.grandpa)
  await expect(filters.getByLabel('Sort', { exact: true })).toHaveValue('newest')
  await filters.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page).not.toHaveURL(/recipient=|when=|status=/)
  await expect(filters.getByRole('checkbox', { name: 'People', exact: true })).toBeVisible()
  await filters.getByRole('checkbox', { name: 'Tasks', exact: true }).uncheck()
  await expect(page).toHaveURL(/type=/)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page).toHaveURL(/\/home$/)
})

test('mobile Home keeps creation available in empty and failed-load states', async ({ page, isMobile, isolatedData }) => {
  test.skip(!isMobile, 'Phone empty and error actions')
  const api = await authenticatedApi(page, isolatedData.apiURL)
  const response = await api('/families', { method: 'POST', data: { name: 'Empty button audit' } })
  expect(response.status()).toBe(201)
  const { family } = await response.json()
  await login(page)
  await page.evaluate(id => sessionStorage.setItem('activeFamilyId', id), family.id)
  await page.goto('/home')
  await visibleButton(page, 'New task').click()
  await expect(page).toHaveURL(/\/tasks\/new$/)
  await page.goto('/home')
  await visibleButton(page, 'Care recipients').click()
  const people = page.getByRole('dialog', { name: 'Your family circle' })
  await expect(people.getByRole('link', { name: 'Add care recipient' })).toBeVisible()
  await people.getByRole('button', { name: 'Close dialog' }).click()
  const url = `**/api/families/${family.id}/tasks`
  await page.route(url, route => route.fulfill({ status: 503, json: { error: 'Temporary task outage' } }))
  await page.goto('/home')
  await expect(visibleButton(page, 'New task')).toBeVisible()
  const retry = page.getByRole('region', { name: 'Family tasks', exact: true }).getByRole('button', { name: 'Try again', exact: true })
  await expect(retry).toBeVisible()
  await page.unroute(url)
  await retry.click()
  await expect(retry).not.toBeVisible()
  await expect(visibleButton(page, 'New task')).toBeVisible()
})
